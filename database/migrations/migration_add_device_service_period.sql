--
-- ระหว่างที่ยังตรวจไม่ครบ แดชบอร์ดจะรายงานความครบถ้วนว่า "ยังยืนยันไม่ได้" พร้อม
-- จำนวนเครื่องที่เหลือ แทนการประกาศว่าครบหรือค้าง ซึ่งทั้งสองคำเป็นข้อสรุปที่
-- หลักฐานยังไม่พอจะพูด — ดู packages/domain/coverage.cjs
--
-- หลังรันเสร็จ: เข้าหน้า "ตรวจยืนยันการติดตั้ง" (ผู้ดูแลระบบ) แล้วไล่ยืนยันทีละเครื่อง
-- ตัวเลขความครบถ้วนจะกลับมาใช้งานได้เมื่อตรวจครบทุกเครื่อง
