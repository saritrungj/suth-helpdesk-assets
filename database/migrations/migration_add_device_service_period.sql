-- ------------------------------------------------------------------------------
-- 1. สถานะการติดตั้ง แยกจากสถานะการใช้งาน
-- ------------------------------------------------------------------------------
-- ห้ามใส่ DEFAULT ที่ไม่ใช่ NULL — ค่า default ใดๆ คือการเดาแทนผู้ดูแล
--
-- service_unverified_before คือเส้นแบ่งระหว่าง "รู้ว่าไม่ต้องกรอก" กับ "ไม่รู้"
--   NULL   = ยืนยันครบทุกช่วงเวลา
--   วันที่ = ก่อนวันนี้ยังยืนยันไม่ได้ (Q21)
-- จำเป็นเพราะผู้ดูแลตอบข้อเท็จจริงปัจจุบันได้ทันที แต่ตอบย้อนหลังได้ต่อเมื่อมีเอกสาร
ALTER TABLE devices
    ADD COLUMN installation_status ENUM('installed','not_installed') DEFAULT NULL AFTER status,
    ADD COLUMN service_unverified_before DATE DEFAULT NULL AFTER installation_status;

-- ------------------------------------------------------------------------------
-- 2. ช่วงเวลาความรับผิดชอบ
-- ------------------------------------------------------------------------------
CREATE TABLE device_service_period (
    id INT AUTO_INCREMENT PRIMARY KEY,
    device_id INT NOT NULL,

    effective_from DATE NOT NULL,
    effective_to DATE NULL,

    note VARCHAR(255) NULL,

    verified_by INT NULL,
    verified_at TIMESTAMP NULL DEFAULT NULL,

    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    FOREIGN KEY (device_id) REFERENCES devices(id) ON DELETE CASCADE,
    FOREIGN KEY (verified_by) REFERENCES users(id),

    INDEX idx_device_service (device_id, effective_from, effective_to),

    CONSTRAINT chk_device_service_period_order CHECK (
        effective_to IS NULL OR effective_to >= effective_from
    )
);

