// บอกเบราว์เซอร์ว่าคำตอบนี้เก็บไว้ใช้ซ้ำได้นานแค่ไหน
//
// สิ่งที่มีอยู่แล้วและสิ่งที่ขาด: Express สร้าง ETag ให้ทุกคำตอบที่ส่งด้วย res.json()
// อยู่แล้วโดยค่าเริ่มต้น และตอบ 304 ให้เองถ้าเบราว์เซอร์ส่ง `If-None-Match` กลับมา
// สิ่งที่ขาดไปคือ `Cache-Control` — ถ้าไม่บอก เบราว์เซอร์จะไม่รู้ว่าเก็บคำตอบนี้ไว้
// ได้หรือเปล่า จึงยิงคำขอเต็มรูปแบบใหม่ทุกครั้ง และ ETag ที่มีอยู่ก็ไม่เคยถูกใช้เลย
//
// ผลของการเติมสองบรรทัดนี้กับรายการอาคาร/ชั้น/ฝ่าย/แผนก/ยี่ห้อ: คำขอที่สองเป็นต้นไป
// ได้ 304 ตัวเปล่า (ไม่กี่ร้อยไบต์) แทน JSON เต็มก้อน — สำคัญกับเครื่องในโรงพยาบาล
// ที่ต่อผ่านเครือข่ายภายในซึ่งช้ากว่าที่คิด
//
// หมายเหตุ: นี่เป็นคนละชั้นกับ cache ของ TanStack Query ฝั่งเว็บ (ADR-0009) —
// ฝั่งนั้นตัด "การยิงคำขอ" ออกทั้งคำขอ ส่วนชั้นนี้ทำให้คำขอที่ยังยิงอยู่ถูกลง
// ทั้งสองชั้นทำงานร่วมกัน ไม่ทับกัน

/**
 * ข้อมูลอ้างอิงที่แทบไม่เปลี่ยน (อาคาร ชั้น ฝ่าย แผนก ยี่ห้อ ปีงบ)
 *
 * - `private` เพราะคำตอบผูกกับผู้ใช้ที่ล็อกอินอยู่ ห้ามให้ proxy กลางเก็บไว้แจกคนอื่น
 * - `max-age=60` ใช้ซ้ำได้เงียบๆ หนึ่งนาทีโดยไม่ถามเซิร์ฟเวอร์เลย
 * - `stale-while-revalidate=600` สิบนาทีถัดมายังแสดงของเดิมได้ทันทีระหว่างที่
 *   ดึงของใหม่อยู่เบื้องหลัง — หน้าจึงไม่เคยค้างรอข้อมูลที่แทบไม่เคยเปลี่ยน
 * - `must-revalidate` เมื่อพ้นช่วงนั้นแล้วต้องถามก่อนเสมอ ห้ามเดาเอง
 */
const referenceData = (res) => {
  res.set("Cache-Control", "private, max-age=60, stale-while-revalidate=600, must-revalidate");
};

/**
 * ข้อมูลที่เปลี่ยนระหว่างวัน (ทะเบียนเครื่อง ยอดพิมพ์ รายงาน)
 *
 * max-age=0 แปลว่า "ถามทุกครั้ง" แต่ยังได้ประโยชน์จาก ETag เต็มที่ — ถ้าไม่มีอะไร
 * เปลี่ยนจะได้ 304 ตัวเปล่ากลับมาแทนที่จะโหลด JSON ทั้งก้อนซ้ำ
 */
const operationalData = (res) => {
  res.set("Cache-Control", "private, max-age=0, must-revalidate");
};

/**
 * คำตอบที่ห้ามเก็บเด็ดขาด — ข้อมูลผู้ใช้ สถานะ session และทุกอย่างหลังการเขียนข้อมูล
 *
 * `no-store` ต่างจาก `no-cache`: no-cache ยังเก็บลงดิสก์แต่ต้องถามก่อนใช้
 * ส่วน no-store คือห้ามเขียนลงที่เก็บใดๆ เลย ซึ่งเป็นสิ่งที่ต้องการสำหรับข้อมูลบัญชี
 * บนเครื่องที่ใช้ร่วมกันหลายคนอย่างเครื่องในหน่วยงาน
 */
const noStore = (res) => {
  res.set("Cache-Control", "no-store");
};

module.exports = { referenceData, operationalData, noStore };
