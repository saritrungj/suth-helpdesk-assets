export function documentTitle(page) {
  return page ? `${page} · ${APP_NAME_SHORT}` : `${APP_NAME} · ${ORG_NAME_SHORT}`;
}

/**
 * ช่องทางติดต่อสำหรับขอสิทธิ์เข้าใช้งาน
 *
 * ⚠️ ตั้งใจให้ว่างไว้ — **ห้ามใส่เบอร์หรืออีเมลสมมติ** หน้านี้เป็นหน้าที่คนจะ
 * โทรหรือส่งเมลตามจริง ข้อมูลปลอมบนหน้านี้แย่กว่าการไม่มีข้อมูล เพราะมันพา
 * คนไปหาปลายทางที่ผิดโดยที่เขาเชื่อว่าถูก
 *
 * เมื่อได้ข้อมูลจริงแล้วให้เติมที่นี่ที่เดียว หน้าล็อกอินจะขึ้นปุ่มให้อัตโนมัติ
 * ถ้า array นี้ว่าง หน้าล็อกอินจะแสดงเพียงข้อความว่าให้ติดต่อ OWNER_TEAM
 * ซึ่งเป็นความจริงที่ยืนยันได้ ไม่ใช่ค่าที่แต่งขึ้น
 *
 * รูปแบบของแต่ละรายการ
 *   kind   "phone" | "email" | "link"  — ใช้เลือกไอคอนและสร้าง href
 *   label  ข้อความที่ผู้ใช้เห็น เช่น "ต่อ 1234"
 *   value  ค่าที่เอาไปทำ href เช่น "021234567", "it@example.ac.th"
 *   note   คำอธิบายเสริม เช่น "จันทร์–ศุกร์ 08:30–16:30" (ไม่ใส่ก็ได้)
 *
 * @type {{kind: "phone" | "email" | "link", label: string, value: string, note?: string}[]}
 */
export const SUPPORT_CHANNELS = [];

/**
 * สร้าง href ของช่องทางติดต่อหนึ่งรายการ
 *
 * แยกออกมาเป็นฟังก์ชันเพราะการเขียน `tel:` ต้องตัดช่องว่างและขีดออกก่อน
 * ไม่งั้นเครื่องบางรุ่นจะไม่ยอมโทรให้
 */
export function supportHref(channel) {
  if (channel.kind === "phone") return `tel:${channel.value.replace(/[^\d+]/g, "")}`;
  if (channel.kind === "email") return `mailto:${channel.value}`;
  return channel.value;
}
