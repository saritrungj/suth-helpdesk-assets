import { QueryClient } from "@tanstack/vue-query";

/**
 * query-client.js — ตัว cache กลางของทั้งแอป และการล้างเมื่อเปลี่ยนบัญชี
 *
 * ## ทำไมต้องสร้างเอง ไม่ปล่อยให้ VueQueryPlugin สร้างให้
 *
 * เพราะต้องมีคนถือ reference ไว้สั่งล้างได้จากนอก component — การเปลี่ยนบัญชี
 * เกิดที่ store/auth.js ซึ่งไม่ได้อยู่ใน component tree จึงเรียก useQueryClient() ไม่ได้
 *
 * ## ทำไมต้องล้างเมื่อเปลี่ยนบัญชี
 *
 * cache นี้มีอายุเท่ากับ SPA ไม่ใช่เท่ากับ session — logout เดิมเคลียร์แค่ auth
 * state ส่วนข้อมูลที่ดึงมาแล้วยังอยู่ครบ และ query key ไม่ได้ผูกกับผู้ใช้
 * ล็อกอินด้วยบัญชีอื่นบนเครื่องเดียวกันจึงอ่านของเดิมต่อได้โดยยังไม่ถาม API ใหม่
 *
 * ⚠️ ขณะที่เขียนนี้ สิทธิ์ "อ่าน" ของหลายบทบาทเหมือนกัน จึง **ยังไม่ได้พิสูจน์ว่า
 * มีข้อมูลรั่วข้ามบทบาทจริง** นี่คือการปิดความเสี่ยงเชิงโครงสร้างไว้ก่อนที่สิทธิ์
 * อ่านจะเริ่มต่างกัน ไม่ใช่การแก้ช่องโหว่ที่ยืนยันแล้ว (ดู issue #29)
 */
export const queryClient = new QueryClient({
  defaultOptions: {
    queries: {
      // ลองซ้ำครั้งเดียวพอ เครือข่ายภายในโรงพยาบาลสะดุดเป็นช่วงสั้นๆ ได้
      // แต่การลองซ้ำหลายรอบทำให้ผู้ใช้รอนานโดยไม่มีอะไรบอกว่าเกิดอะไรขึ้น
      retry: 1,

      // คนที่นี่สลับไปโปรแกรมอื่นแล้วกลับมาตลอดเวลา การยิงใหม่ทุกครั้งที่กลับมา
      // ที่แท็บทำให้ตัวเลขขยับเองระหว่างที่กำลังอ่านอยู่ — การรีเฟรชเมื่อข้อมูล
      // เก่าเกิน staleTime ยังทำงานตามปกติ
      refetchOnWindowFocus: false,
    },
  },
});

/**
 * ล้าง cache ทั้งหมดเพราะ "คนที่ใช้อยู่" เปลี่ยนไปแล้ว
 *
 * ลำดับตั้งใจ: `clear()` ก่อน แล้วค่อยยกเลิกคำขอที่ค้างอยู่
 *
 * `clear()` ทำงานทันทีแบบ synchronous — ข้อมูลของบัญชีเก่าอ่านไม่ได้ตั้งแต่วินาที
 * ที่ฟังก์ชันนี้คืนค่า ส่วน `cancelQueries()` เป็น async ถ้ารอมันก่อนจะเหลือช่วง
 * เวลาที่ข้อมูลเก่ายังอ่านได้อยู่ คำตอบของคำขอที่ค้างจะไปตกใส่ query ที่ถูกถอด
 * ออกจาก cache ไปแล้ว จึงไม่ย้อนกลับมาทับ
 */
export function resetQueryCacheForNewIdentity() {
  queryClient.clear();

  // ไม่ await — ผู้เรียก (setAuth/clearAuth) เป็น synchronous และไม่ควรถูกบล็อก
  // ด้วยการยกเลิกคำขอ ซึ่งเป็นแค่การเก็บกวาดไม่ให้เปลืองเครือข่าย
  queryClient.cancelQueries().catch(() => {});
}
