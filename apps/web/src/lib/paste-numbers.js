/**
 * paste-numbers.js — อ่านตัวเลขที่ผู้ใช้คัดลอกมาจากตารางคำนวณ
 *
 * ## ทำไมต้องมีไฟล์นี้
 *
 * เจ้าหน้าที่ไล่อ่านมิเตอร์แล้วจดลงตารางคำนวณ (Excel / Google Sheets) ก่อนแทบทุกครั้ง
 * การบังคับให้มาพิมพ์ซ้ำทีละช่องสิบสองครั้งต่อเครื่อง คูณด้วยจำนวนเครื่องเป็นร้อย
 * คือที่มาของเวลาส่วนใหญ่ที่หมดไปกับระบบนี้ และเป็นจุดที่เกิดการพิมพ์ผิดมากที่สุด
 *
 * แยกออกมาจากหน้าจอเพราะเป็นตรรกะล้วนที่มีกรณีขอบเยอะ และต้องทดสอบได้โดยไม่ต้อง
 * เปิดเบราว์เซอร์ — ดู paste-numbers.test.js
 *
 * ## สิ่งที่ต้องรับมือ (เจอจริงทั้งหมด)
 *
 * - ตัวคั่นหลักพันที่ติดมาด้วย: `"12,480"`
 * - ช่องว่างไม่ตัดคำ (U+00A0) ที่ตารางคำนวณบางตัวใส่มาแทนช่องว่างปกติ
 * - คัดลอกเป็นคอลัมน์ (คั่นด้วยขึ้นบรรทัด) หรือเป็นแถว (คั่นด้วย tab)
 * - แถวหัวตารางหรือข้อความอื่นที่ติดมาด้วย
 * - ช่องที่ว่างจริงๆ ในตารางต้นทาง
 */

/**
 * ผลของการอ่านหนึ่งช่อง
 *
 * แยกสามสถานะให้ชัดเจน เพราะแต่ละอันต้องทำคนละอย่าง
 *
 *   number     ค่าที่ใช้ได้ — เขียนทับช่องปลายทาง
 *   null       ช่องว่างในต้นทาง — แปลว่า "ยังไม่ได้กรอก" ไม่ใช่ "พิมพ์ศูนย์แผ่น"
 *              สองอย่างนี้ต่างกันในรายงานความคืบหน้า (ดู print-usage/routes.js)
 *   undefined  แปลงเป็นตัวเลขไม่ได้ — ข้ามช่องนั้นไปโดย **ไม่แตะค่าเดิม** และต้อง
 *              นับไว้บอกผู้ใช้ การกลืนหายไปเงียบๆ อันตรายกว่าการวางไม่ติดเลย
 *              เพราะผู้ใช้จะเชื่อว่าวางครบแล้วทั้งที่ขาดไป
 *
 * @typedef {number|null|undefined} ParsedCell
 */

/**
 * แปลงข้อความจากคลิปบอร์ดเป็นรายการค่า เรียงตามลำดับที่คัดลอกมา
 *
 * @param {string} text ข้อความดิบจาก clipboardData
 * @returns {ParsedCell[]}
 */
export function parseNumbers(text) {
  return String(text ?? "")
    .trim()
    .split(/\r?\n/)
    .flatMap((line) => line.split("\t"))
    .map((cell) => {
      // ลบตัวคั่นหลักพัน ช่องว่างปกติ และช่องว่างไม่ตัดคำออกก่อนแปลง
      const cleaned = cell.replace(/[,\s\u00a0]/g, "");
      if (!cleaned) return null;

      const value = Number(cleaned);

      // ยอดพิมพ์ติดลบไม่มีอยู่จริง ถือเป็นค่าที่ใช้ไม่ได้เหมือนข้อความ
      // และปัดเป็นจำนวนเต็มเสมอ เพราะมิเตอร์นับเป็นแผ่น ไม่มีเศษแผ่น
      if (!Number.isFinite(value) || value < 0) return undefined;

      return Math.round(value);
    });
}

/**
 * เติมค่าที่วางมาลงในรายการเป้าหมาย เริ่มจากตำแหน่งที่ระบุ
 *
 * รักษาการเรียงตามตำแหน่งไว้เสมอ — ช่องที่แปลงไม่ได้จะ "เว้นที่ไว้" ไม่ใช่ทำให้
 * ค่าที่เหลือเลื่อนขึ้นมาแทน เพราะการเลื่อนจะทำให้ยอดของทั้งปีผิดตำแหน่งทุกเดือน
 * จากความผิดพลาดเล็กๆ ที่ต้นทางเพียงจุดเดียว
 *
 * ไม่แก้ไข target โดยตรง — คืนค่าใหม่ออกไป ให้ผู้เรียกตัดสินใจว่าจะเขียนทับเมื่อไหร่
 * (และเก็บของเดิมไว้ให้กดเลิกทำได้)
 *
 * @param {(number|null)[]} target ค่าปัจจุบันของทุกช่อง
 * @param {ParsedCell[]} values ค่าที่วางมา
 * @param {number} startIndex ตำแหน่งของช่องที่กำลังโฟกัส
 * @returns {{ values: (number|null)[], filled: number, skipped: number, overflow: number }}
 */
export function applyPaste(target, values, startIndex = 0) {
  const next = [...target];
  let filled = 0;
  let skipped = 0;

  values.forEach((value, offset) => {
    const index = startIndex + offset;
    if (index >= next.length) return;

    if (value === undefined) {
      skipped += 1;
      return;
    }

    next[index] = value;
    filled += 1;
  });

  return {
    values: next,
    filled,
    skipped,
    // ค่าที่ล้นออกนอกจำนวนช่องที่มี — ต้องบอกผู้ใช้ ไม่ใช่ทิ้งเงียบๆ
    // มักแปลว่าคัดลอกมาผิดคอลัมน์หรือรวมหัวตารางมาด้วย
    overflow: Math.max(0, values.length - (next.length - startIndex)),
  };
}

/**
 * สรุปผลการวางเป็นข้อความเดียวที่บอกสิ่งที่เกิดขึ้นจริง
 *
 * "วาง 7 เดือน · ข้าม 1 ค่าที่ไม่ใช่ตัวเลข" มีประโยชน์กว่า "วางสำเร็จ" เพราะ
 * ผู้ใช้ตรวจได้ทันทีว่าตรงกับที่ตั้งใจไหม ก่อนจะกดบันทึก
 *
 * @param {{ filled: number, skipped: number, overflow: number }} result
 * @returns {string}
 */
export function describePaste({ filled, skipped, overflow }) {
  const parts = [`วาง ${filled} เดือน`];
  if (skipped) parts.push(`ข้าม ${skipped} ค่าที่ไม่ใช่ตัวเลข`);
  if (overflow) parts.push(`เกินมา ${overflow} ค่าไม่ถูกใช้`);
  return parts.join(" · ");
}
