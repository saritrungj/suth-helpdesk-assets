import { expect, test } from "vitest";
import { csvCell, toCsv } from "./export-csv";

/*
 * เทสชุดนี้คุ้มกัน #87 — ไฟล์ "รายการที่ต้องแก้" เคยเอาค่าจากไฟล์ที่ผู้ใช้อัปโหลด
 * ใส่ลงเซลล์ตรงๆ โดยครอบด้วยคำพูดคู่อย่างเดียว ซึ่งเป็นการ escape ของรูปแบบ CSV
 * ไม่ใช่การบอกโปรแกรมตารางว่าข้างในเป็นข้อความ
 */

test("ค่าธรรมดาถูกครอบด้วยคำพูดคู่ตามรูปแบบ CSV", () => {
  expect(csvCell("PRN-OPD-001")).toBe('"PRN-OPD-001"');
  expect(csvCell(42)).toBe('"42"');
});

test("ค่าว่างและ null กลายเป็นเซลล์ว่าง ไม่ใช่คำว่า null", () => {
  expect(csvCell(null)).toBe('""');
  expect(csvCell(undefined)).toBe('""');
  expect(csvCell("")).toBe('""');
});

test("คำพูดคู่ข้างในถูก escape เป็นสองตัวตามเดิม", () => {
  expect(csvCell('ไม่พบเครื่อง SN "X" ในระบบ')).toBe('"ไม่พบเครื่อง SN ""X"" ในระบบ"');
});

test("ค่าที่ขึ้นต้นด้วยตัวเริ่มสูตร ถูกบังคับให้เป็นข้อความ", () => {
  expect(csvCell("=1+1")).toBe("\"'=1+1\"");
  expect(csvCell("+1+1")).toBe("\"'+1+1\"");
  expect(csvCell("-1+1")).toBe("\"'-1+1\"");
  expect(csvCell("@SUM(A1)")).toBe("\"'@SUM(A1)\"");
  expect(csvCell("\tcmd")).toBe("\"'\tcmd\"");
});

test("สูตรสั่งงานผ่าน DDE ก็ถูกบังคับให้เป็นข้อความเหมือนกัน", () => {
  expect(csvCell("=cmd|' /C calc'!A0")).toBe("\"'=cmd|' /C calc'!A0\"");
});

test("ตัวเริ่มสูตรที่อยู่กลางข้อความไม่ถูกแตะ — เส้นแบ่งอยู่ที่ตัวอักษรแรกเท่านั้น", () => {
  expect(csvCell("SN=123")).toBe('"SN=123"');
  expect(csvCell("A+B")).toBe('"A+B"');
});

test("เลขติดลบยังอ่านออกได้ แม้ถูกบังคับเป็นข้อความ", () => {
  // ยอมแลกความเป็นตัวเลขกับความปลอดภัย เพราะไฟล์นี้มีไว้ให้คนอ่านแล้วไปแก้ไฟล์ต้นทาง
  // ไม่ได้มีไว้ให้เอาไปคำนวณต่อ — และค่าติดลบในนี้คือค่าที่ระบบปฏิเสธไปแล้ว
  expect(csvCell(-5)).toBe("\"'-5\"");
});

test("toCsv ต่อทั้งตารางด้วย CRLF ตาม RFC 4180", () => {
  expect(toCsv([["แถว", "Serial"], [3, "=1+1"]])).toBe('"แถว","Serial"\r\n"3","\'=1+1"');
});
