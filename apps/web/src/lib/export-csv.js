// การครอบด้วย `"` เป็นกลไก escape ของ **รูปแบบไฟล์ CSV** ไม่ใช่การบอกโปรแกรม
// ตารางว่า "ข้างในนี้เป็นข้อความ" โปรแกรมอ่านค่าออกมาก่อน แล้วค่อยตัดสินว่าจะ
// ตีความเป็นสูตรไหม ค่าที่ขึ้นต้นด้วย = + - @ จึงยังทำงานเป็นสูตรได้แม้ถูกครอบไว้
//
// ที่นี่จึงเติม `'` นำหน้าค่าที่เสี่ยง ซึ่งเป็นวิธีที่โปรแกรมตารางทุกตัวเข้าใจตรงกัน
// ว่า "บังคับให้เป็นข้อความ" และผู้อ่านไฟล์ยังเห็นค่าเดิมครบทุกตัวอักษร
//
// ## ทำไมถึงสำคัญกับไฟล์ "รายการที่ต้องแก้" เป็นพิเศษ (#87)
//
// ไฟล์นั้นคือรายการค่าที่ระบบ **ปฏิเสธ** ไป ซึ่งแปลว่ามันคือค่าที่แปลกที่สุดในไฟล์
// ต้นทางเสมอ ยิ่งตัวตรวจทำงานดี ค่าที่อันตรายก็ยิ่งถูกคัดมารวมกันไว้ในไฟล์ที่ผู้ใช้
// จะกดเปิดอ่าน

/** ตัวอักษรที่โปรแกรมตารางถือว่าเป็นจุดเริ่มของสูตร */
const FORMULA_STARTERS = ["=", "+", "-", "@", "\t", "\r"];

/**
 * ค่าหนึ่งเซลล์ในรูปแบบ CSV — บังคับให้เป็นข้อความเสมอ
 *
 * @param {unknown} value
 * @returns {string} เซลล์ที่ครอบและ escape แล้ว พร้อมต่อด้วย comma ได้ทันที
 */
export function csvCell(value) {
  let text = String(value ?? "");
  if (FORMULA_STARTERS.includes(text[0])) text = `'${text}`;
  return `"${text.replaceAll('"', '""')}"`;
}

/**
 * ประกอบทั้งไฟล์จากตารางสองมิติ
 *
 * ใช้ CRLF ตาม RFC 4180 และผู้เรียกเป็นคนเติม BOM เองตอนสร้าง Blob เพราะ BOM
 * เป็นเรื่องของการเข้ารหัสไฟล์ ไม่ใช่ของเนื้อหา
 *
 * @param {unknown[][]} rows แถวแรกคือหัวตาราง
 */
export function toCsv(rows) {
  return rows.map((row) => row.map(csvCell).join(",")).join("\r\n");
}
